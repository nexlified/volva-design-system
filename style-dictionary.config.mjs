// Single token source (tokens/**) -> CSS vars for Drupal/Storybook, Dart for Flutter, JSON for reference.
import StyleDictionary from 'style-dictionary';

const PREFIX = 'vds';
const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const camel = (parts) =>
  parts.map((p, i) => (i === 0 ? p : pascal(p))).join('').replace(/^(\d)/, 'n$1');

const dartColor = (hex) => {
  const h = hex.replace('#', '');
  const [rgb, a] = h.length === 8 ? [h.slice(0, 6), h.slice(6)] : [h, 'FF'];
  return `Color(0x${(a + rgb).toUpperCase()})`;
};
const px = (v) => {
  const n = parseFloat(v);
  return v.endsWith('rem') ? n * 16 : n;
};

function dartValue(token) {
  const v = token.$value;
  switch (token.$type) {
    case 'color': return { type: 'Color', code: dartColor(v) };
    case 'dimension': return { type: 'double', code: String(px(v)) };
    case 'number': return { type: 'double', code: String(v) };
    case 'fontWeight': return { type: 'FontWeight', code: `FontWeight.w${v}` };
    case 'duration': return { type: 'Duration', code: `Duration(milliseconds: ${parseFloat(v)})` };
    case 'fontFamily': return { type: 'String', code: JSON.stringify(Array.isArray(v) ? v[0] : v) };
    case 'shadow':
      return {
        type: 'BoxShadow',
        code: `BoxShadow(color: ${dartColor(v.color)}, offset: Offset(${px(v.offsetX)}, ${px(v.offsetY)}), blurRadius: ${px(v.blur)}, spreadRadius: ${px(v.spread)})`,
      };
    default: return null;
  }
}

StyleDictionary.registerFormat({
  name: 'vds/dart',
  format: ({ dictionary }) => {
    const groups = new Map();
    for (const t of dictionary.allTokens) {
      const dv = dartValue(t);
      if (!dv) continue;
      const [root, ...rest] = t.path;
      if (!groups.has(root)) groups.set(root, []);
      groups.get(root).push(`  static const ${dv.type} ${camel(rest)} = ${dv.code};`);
    }
    const body = [...groups].map(([root, lines]) =>
      `abstract final class Vds${pascal(root)}Tokens {\n${lines.join('\n')}\n}`).join('\n\n');
    return `// GENERATED by style-dictionary.config.mjs — do not edit.\nimport 'package:flutter/painting.dart';\n\n${body}\n`;
  },
});

// Raw (untransformed) values for Dart: aliases are resolved, units handled by the format.
StyleDictionary.registerTransform({ name: 'vds/name-path', type: 'name', transform: (t) => t.path.join('.') });
StyleDictionary.registerTransformGroup({ name: 'vds/dart', transforms: ['vds/name-path'] });

const sd = new StyleDictionary({
  source: ['tokens/**/*.json'],
  platforms: {
    css: {
      transformGroup: 'css',
      prefix: PREFIX,
      buildPath: 'dist/css/',
      files: [{ destination: 'tokens.css', format: 'css/variables', options: { outputReferences: true, selector: ':root' } }],
    },
    json: {
      transformGroup: 'css',
      buildPath: 'dist/json/',
      files: [{ destination: 'tokens.json', format: 'json/nested' }],
    },
    dart: {
      transformGroup: 'vds/dart',
      buildPath: 'packages/volva_ds_flutter/lib/src/tokens/',
      files: [{ destination: 'vds_tokens.dart', format: 'vds/dart' }],
    },
  },
});

await sd.buildAllPlatforms();
